MAX_WORKERS = 4
_executor = concurrent.futures.ThreadPoolExecutor(max_workers=MAX_WORKERS)
atexit.register(lambda: _executor.shutdown(wait=True))

def thread_start(func, args=()):
    """Starts a new thread."""
    import threading
    thread = threading.Thread(target=func, args=args)
    thread.start()
    return thread

def thread_join(thread):
    """Waits for a thread to complete."""
    if thread:
        thread.join()

def submit_task(func, *args, **kwargs):
    """Submits a task to the global thread pool."""
    if not callable(func):
        raise TypeError("Only callable objects can be submitted as tasks.")
    return _executor.submit(func, *args, **kwargs)

def get_future_result(future, timeout=None):
    """Gets the result from a future object."""
    if not isinstance(future, concurrent.futures.Future):
        return "Invalid input: not a future object."
    try:
        return future.result(timeout=timeout)
    except concurrent.futures.TimeoutError:
        return "Timeout: Task did not complete in time."
    except Exception as e:
        return f"Task failed with an exception: {e}"

def is_future_done(future):
    """Checks if a future is done."""
    if not isinstance(future, concurrent.futures.Future):
        return False
    return future.done()

# --- Filesystem & I/O Runtime Helpers ---

class VirtualFileSystem:
    """A simple in-memory virtual filesystem."""
    def __init__(self):
        self._fs = {"/": {}}

    def _normalize_path(self, path):
        return os.path.normpath(os.path.join("/", path))

    def _get_node(self, path, create=False):
        parts = self._normalize_path(path).strip("/").split("/")
        node = self._fs["/"]
        for part in parts:
            if not part:
                continue
            if part not in node:
                if create:
                    node[part] = {}
                else:
                    return None
            node = node[part]
        return node

    def write_file(self, path, content):
        if not isinstance(content, str):
            content = str(content)
        dirname, basename = os.path.split(self._normalize_path(path))
        parent_node = self._get_node(dirname, create=True)
        if parent_node is None or not isinstance(parent_node, dict):
            return {"error": "Invalid path"}
        parent_node[basename] = content
        return {"status": "success"}

    def read_file(self, path):
        dirname, basename = os.path.split(self._normalize_path(path))
        parent_node = self._get_node(dirname)
        if parent_node and basename in parent_node and isinstance(parent_node[basename], str):
            return parent_node[basename]
        return {"error": "File not found"}

    def list_dir(self, path):
        node = self._get_node(path)
        if isinstance(node, dict):
            return list(node.keys())
        return {"error": "Directory not found"}

    def append_file(self, path, content):
        if not isinstance(content, str):
            content = str(content)
        current_content = self.read_file(path)
        if isinstance(current_content, dict) and "error" in current_content:
            return self.write_file(path, content)
        return self.write_file(path, current_content + content)

    def delete_file(self, path):
        dirname, basename = os.path.split(self._normalize_path(path))
        parent_node = self._get_node(dirname)
        if parent_node and basename in parent_node:
            del parent_node[basename]
            return {"status": "success"}
        return {"error": "File not found"}

    def file_exists(self, path):
        dirname, basename = os.path.split(self._normalize_path(path))
        parent_node = self._get_node(dirname)
        return parent_node is not None and basename in parent_node

    def mkdir(self, path):
        node = self._get_node(path, create=True)
        if node is not None:
            return {"status": "success"}
        return {"error": "Could not create directory"}

    def temp_file(self):
        import uuid
        path = f"/tmp/{uuid.uuid4()}"
        self.write_file(path, "")
        return path

    def copy_file(self, src, dst):
        content = self.read_file(src)
        if isinstance(content, dict) and "error" in content:
            return content
        return self.write_file(dst, content)

