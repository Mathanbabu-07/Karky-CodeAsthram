# --- Dictionary & Mapping Runtime Helpers ---

def deep_merge(d1, d2):
    """Recursively merges two dictionaries."""
    for k, v in d2.items():
        if k in d1 and isinstance(d1[k], dict) and isinstance(v, collections.abc.Mapping):
            d1[k] = deep_merge(d1[k], v)
        else:
            d1[k] = v
    return d1

def get_nested(d, path, default=None):
    """Safely gets a value from a nested dictionary using a list of keys."""
    if not isinstance(d, dict) or not isinstance(path, list):
        return default
    for key in path:
        if not isinstance(d, dict) or key not in d:
            return default
        d = d[key]
    return d

def set_nested(d, path, value):
    """Safely sets a value in a nested dictionary using a list of keys."""
    if not isinstance(d, dict) or not isinstance(path, list):
        return
    for key in path[:-1]:
        d = d.setdefault(key, {})
    d[path[-1]] = value

def flatten_dict(d, parent_key='', sep='.'):
    """Flattens a nested dictionary."""
    items = []
    for k, v in d.items():
        new_key = parent_key + sep + k if parent_key else k
        if isinstance(v, collections.abc.Mapping):
            items.extend(flatten_dict(v, new_key, sep=sep).items())
        else:
            items.append((new_key, v))
    return dict(items)

def unflatten_dict(d):
    """Unflattens a dictionary with dot-separated keys."""
    result = {}
    for k, v in d.items():
        parts = k.split('.')
        d_nested = result
        for part in parts[:-1]:
            d_nested = d_nested.setdefault(part, {})
        d_nested[parts[-1]] = v
    return result

