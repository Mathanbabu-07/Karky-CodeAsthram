# --- Core Fundamentals Runtime Helpers ---

def create_enum(name: str, members: list):
    """Safely creates an Enum class."""
    if not isinstance(name, str) or not all(isinstance(m, str) for m in members):
        return enum.Enum(name, [])
    return enum.Enum(name, {member: member for member in members})

def create_dataclass(name: str, fields: list):
    """Safely creates a dataclass."""
    if not isinstance(name, str) or not all(isinstance(f, str) for f in fields):
        return None
    from dataclasses import dataclass
    new_type = type(name, (), {'__annotations__': {field: typing.Any for field in fields}})
    return dataclass(new_type)

def create_namedtuple(name: str, field_names: list):
    """Safely creates a namedtuple."""
    if not isinstance(name, str) or not all(isinstance(f, str) for f in field_names):
        return None
    return collections.namedtuple(name, field_names)

# --- Records & Structs Runtime Helpers ---

def create_dataclass_with_defaults(name: str, fields: list, defaults: dict):
    """Safely creates a dataclass with default values."""
    from dataclasses import make_dataclass, field
    if not isinstance(name, str) or not all(isinstance(f, str) for f in fields):
        return None

    field_definitions = []
    for f in fields:
        if f in defaults:
            field_definitions.append((f, typing.Any, field(default=defaults[f])))
        else:
            field_definitions.append((f, typing.Any))

    return make_dataclass(name, field_definitions)

def record_to_dict(record):
    """Converts a namedtuple or dataclass instance to a dictionary."""
    if hasattr(record, '_asdict'): # Check for namedtuple
        return record._asdict()
    from dataclasses import is_dataclass, asdict
    if is_dataclass(record):
        return asdict(record)
    return {}

