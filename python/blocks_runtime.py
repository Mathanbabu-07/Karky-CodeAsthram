# --- Testing & Quality Runtime Helpers ---

def run_tests(globals_dict):
    """Discovers and runs all functions in the provided scope that start with 'test_'."""
    results = {"passed": 0, "failed": 0, "errors": 0, "details": []}
    test_functions = [(name, func) for name, func in globals_dict.items() if callable(func) and name.startswith("test_")]
    for name, func in test_functions:
        try:
            func()
            results["passed"] += 1
            results["details"].append({"name": name, "status": "PASSED"})
        except AssertionError as e:
            results["failed"] += 1
            results["details"].append({"name": name, "status": "FAILED", "reason": str(e)})
        except Exception as e:
            results["errors"] += 1
            results["details"].append({"name": name, "status": "ERROR", "reason": str(e)})
    return results

