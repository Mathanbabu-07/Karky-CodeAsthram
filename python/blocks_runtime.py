# --- Loop & Iteration Runtime Helpers ---

class LoopLimitExceeded(Exception):
    """Custom exception for loops that run too long."""
    pass

def limited_iterator(iterable, max_iterations=1000):
    """A generator that wraps an iterable and limits the number of iterations."""
    count = 0
    iterator = iter(iterable)
    while True:
        if count >= max_iterations:
            raise LoopLimitExceeded(f"Loop exceeded maximum of {max_iterations} iterations.")
        try:
            yield next(iterator)
            count += 1
        except StopIteration:
            return

def sliding_window(sequence, size, step):
    """Returns a list of sliding windows over a sequence."""
    if size <= 0 or step <= 0:
        return []
    return [sequence[i:i+size] for i in range(0, len(sequence) - size + 1, step)]

