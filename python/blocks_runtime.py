# Mapping from string names to SQLAlchemy types
_db_type_map = {
    "INTEGER": Integer,
    "STRING": String,
    "FLOAT": Float,
    "BOOLEAN": Boolean,
}

def db_create_engine(connection_string='sqlite:///:memory:'):
    """Creates a new SQLAlchemy engine."""
    if not create_engine:
        return {"error": "The 'SQLAlchemy' library is required."}
    try:
        engine = create_engine(connection_string)
        return engine
    except Exception as e:
        return {"error": f"Failed to create engine: {e}"}

def db_define_table(table_name, engine, columns_def):
    """Defines a table using SQLAlchemy's core Table object and creates it."""
    if not create_engine:
        return {"error": "The 'SQLAlchemy' library is required."}

    metadata = MetaData()
    sqlalchemy_columns = []
    for col_def in columns_def:
        col_type_str = col_def.get("type", "STRING").upper()
        col_type = _db_type_map.get(col_type_str)
        if not col_type:
            return {"error": f"Unsupported column type: {col_type_str}"}

        sqlalchemy_columns.append(
            Column(
                col_def["name"],
                col_type,
                primary_key=col_def.get("primary_key", False),
            )
        )

    try:
        table = Table(table_name, metadata, *sqlalchemy_columns)
        metadata.create_all(engine)  # Create the table in the database
        return table
    except Exception as e:
        return {"error": f"Failed to define table: {e}"}

def db_execute_statement(engine, statement):
    """Executes a SQLAlchemy statement (insert, update, delete)."""
    if not engine:
        return {"error": "Invalid database engine."}
    try:
        with engine.connect() as connection:
            result = connection.execute(statement)
            connection.commit()
            return {"status": "success", "rows_affected": result.rowcount}
    except exc.SQLAlchemyError as e:
        return {"error": "Database Execution Error", "details": str(e)}

def db_fetch_all(engine, statement):
    """Executes a select statement and fetches all results."""
    if not engine:
        return {"error": "Invalid database engine."}
    try:
        with engine.connect() as connection:
            result = connection.execute(statement)
            # .mappings() returns a list of dict-like objects
            return [row._asdict() for row in result.fetchall()]
    except exc.SQLAlchemyError as e:
        return {"error": "Database Fetch Error", "details": str(e)}

def db_fetch_one(engine, statement):
    """Executes a select statement and fetches the first result."""
    if not engine:
        return {"error": "Invalid database engine."}
    try:
        with engine.connect() as connection:
            result = connection.execute(statement)
            row = result.fetchone()
            if row:
                return row._asdict()
            return None
    except exc.SQLAlchemyError as e:
        return {"error": "Database Fetch Error", "details": str(e)}

# --- Cache Helpers ---

_cache = {}
_cache_ttl = {}

def cache_set(key, value, ttl=None):
    """Sets a value in the cache with an optional time-to-live."""
    import time
    _cache[key] = value
    if ttl:
        _cache_ttl[key] = time.time() + ttl

def cache_get(key):
    """Gets a value from the cache."""
    import time
    if key in _cache_ttl and _cache_ttl[key] < time.time():
        del _cache[key]
        del _cache_ttl[key]
        return None
    return _cache.get(key)

def cache_delete(key):
    """Deletes a value from the cache."""
    if key in _cache:
        del _cache[key]
    if key in _cache_ttl:
        del _cache_ttl[key]

def cache_incr(key, by=1):
    """Increments a value in the cache."""
    value = cache_get(key) or 0
    if isinstance(value, (int, float)):
        _cache[key] = value + by
        return _cache[key]
    return None # Or raise an error

