# --- Serialization & Data Formats Runtime Helpers ---

def to_json(data):
    """Safely serializes a Python object to a JSON string."""
    try:
        return json.dumps(data, indent=2)
    except TypeError as e:
        return f'{{"error": "Object not serializable", "details": "{e}"}}'

def from_json(json_string):
    """Safely deserializes a JSON string to a Python object."""
    try:
        return json.loads(json_string)
    except json.JSONDecodeError as e:
        return {"error": "Invalid JSON", "details": str(e)}

def write_csv(path, data_list_of_dicts):
    """Writes a list of dictionaries to a CSV file in the virtual FS."""
    if not data_list_of_dicts or not isinstance(data_list_of_dicts, list) or not data_list_of_dicts:
        return {"error": "Invalid data format; expected a non-empty list of dictionaries."}
    headers = data_list_of_dicts[0].keys()
    string_io = io.StringIO()
    writer = csv.DictWriter(string_io, fieldnames=headers)
    writer.writeheader()
    writer.writerows(data_list_of_dicts)
    return vfs.write_file(path, string_io.getvalue())

def read_csv(path):
    """Reads a CSV file from the virtual FS into a list of dictionaries."""
    csv_content = vfs.read_file(path)
    if isinstance(csv_content, dict) and "error" in csv_content:
        return csv_content
    string_io = io.StringIO(csv_content)
    reader = csv.DictReader(string_io)
    return list(reader)

def load_json(source):
    """Loads JSON from a string or a file path in the virtual FS."""
    if source.startswith('/'): # Assume it's a path
        content = vfs.read_file(source)
        if isinstance(content, dict) and "error" in content:
            return content
        return from_json(content)
    return from_json(source)

def dump_json(obj, dest=None):
    """Dumps an object to a JSON string or a file in the virtual FS."""
    json_str = to_json(obj)
    if dest:
        return vfs.write_file(dest, json_str)
    return json_str

