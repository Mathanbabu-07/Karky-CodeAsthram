def fastapi_create_app():
    """Creates and returns a new FastAPI application instance."""
    if not FastAPI:
        return None
    return FastAPI()

def fastapi_add_endpoint(app, path, handler, methods):
    """Adds an endpoint to the FastAPI application."""
    if not app or not hasattr(app, "add_api_route"):
        return {"error": "Invalid FastAPI app instance."}

    # The handler needs to be registered with the app
    app.add_api_route(path, handler, methods=methods)
    return handler # Return the original handler, as it's now registered

def fastapi_run_server(app, host='127.0.0.1', port=8000):
    """Runs the FastAPI server in a background thread."""
    global _fastapi_server, _fastapi_thread
    if not uvicorn or not threading:
        return {"error": "The 'uvicorn' library is required to run the server."}

    if _fastapi_thread and _fastapi_thread.is_alive():
        return {"error": "A server is already running."}

    config = uvicorn.Config(app, host=host, port=port, log_level="info")
    _fastapi_server = uvicorn.Server(config)

    _fastapi_thread = threading.Thread(target=_fastapi_server.run)
    _fastapi_thread.start()
    return _fastapi_thread

def fastapi_stop_server():
    """Stops the running FastAPI server."""
    global _fastapi_server, _fastapi_thread
    if _fastapi_server and _fastapi_thread and _fastapi_thread.is_alive():
        _fastapi_server.should_exit = True
        _fastapi_thread.join(timeout=2) # Wait for the thread to finish
        _fastapi_server = None
        _fastapi_thread = None
        return {"status": "Server stopped"}
    return {"error": "No server is running."}

